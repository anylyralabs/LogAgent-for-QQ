    private const string PlainFormatRule = """
        回复格式（当前通道不支持 Markdown）：
        · 不要写 **加粗**、# 标题、| 表格 | 这类语法；用短句、换行、数字序号或 · 组织内容。
        · 较长的技术分析（看日志、排障、评测类）按分节组织，分节标题用【】包裹并单独成行：
          【结论】（一句话）→【原因分析】（逐条附证据）→【解决方法】（编号步骤）→【相关建议】/【需要补充】（可选）；
        · 短问答与闲聊不要分节，自然说话即可。
        """;

    private const string MarkdownFormatRule = """
        回复格式（当前通道支持 Markdown）：
        · 使用 Markdown：分节标题用 ##（如 ## 结论），重点用 **加粗**，列表用 - 或数字序号。
        · 不要使用【】中文方括号作为标题或标签。
        · 需要对比多项原因、版本或参数时，优先用 Markdown 表格，让问题本质一眼可见；但最多 3 列（超过会溢出），表格前后各留一个空行，列名尽量短。
        · 较长的技术分析（看日志、排障、评测类）按分节组织：
          ## 结论 → ## 原因分析 → ## 解决方法 → ## 相关建议 / ## 需要补充。
        · 短问答与闲聊不要分节，自然说话即可。
        """;

    /// <summary>按频道能力返回人设提示：官方 Bot 支持 Markdown 时不再使用【】分节。</summary>
    public static string XiaoyanFor(bool markdown) =>
        Xiaoyan + "\n\n" + (markdown ? MarkdownFormatRule : PlainFormatRule);

    /// <summary>
    /// 当前会话元信息：明确告诉模型这是群聊还是私聊，避免把群聊上下文当成单聊、
    /// 或把不同群的上下文混在一起。
    /// </summary>
    public static string ChatContextLine(ChatType chatType, string? channelName = null)
    {
        var channel = string.IsNullOrWhiteSpace(channelName) ? "本机/未知频道" : channelName.Trim();
        if (chatType == ChatType.Private && string.Equals(channel, "本机对话", StringComparison.Ordinal))
            return "当前会话：本机对话（非 QQ 群聊/私聊）。这是与本地操作者的对话。";

        return chatType == ChatType.Group
            ? $"当前会话：QQ 群聊（频道：{channel}）。这是多人群聊，消息以「昵称: 内容」标注；只依据本群上下文回答，不要引用其他群的内容。"
            : $"当前会话：QQ 私聊（频道：{channel}）。这是与单个用户的对话，不要当成群聊。";
    }

